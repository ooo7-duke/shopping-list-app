// A small Excel (.xlsx) writer, so the expense report opens in Excel with real numbers,
// dates and totals, without pulling in a spreadsheet library. An .xlsx file is a zip of XML
// files; this writes the zip uncompressed ("stored"), which Excel and Google Sheets accept.
//
// sheets: [{ name, rows: [[cell]], widths?: [chars], filter?: bool, freeze?: bool }]
// cell:   { v: string | number | Date, s?: 'bold' | 'money' | 'moneyBold' | 'date' | 'title', f?: formula }

const STYLE = { '': 0, bold: 1, money: 2, moneyBold: 3, date: 4, title: 5 };

const esc = (s) => String(s)
  // eslint-disable-next-line no-control-regex
  .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export const colName = (i) => {
  let s = ''; let n = i + 1;
  while (n > 0) { const m = (n - 1) % 26; s = String.fromCharCode(65 + m) + s; n = Math.floor((n - 1) / 26); }
  return s;
};

// Excel counts days from Dec 30, 1899, in local time.
const serial = (d) => (Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) - Date.UTC(1899, 11, 30)) / 86400000;

function cellXml(c, ref) {
  if (c == null || (c.v === '' && !c.f)) return '';
  const s = STYLE[c.s || ''] || 0;
  const sa = s ? ` s="${s}"` : '';
  if (c.f) return `<c r="${ref}"${sa}><f>${esc(c.f)}</f>${typeof c.v === 'number' ? `<v>${c.v}</v>` : ''}</c>`;
  if (c.v instanceof Date) return `<c r="${ref}"${sa}><v>${serial(c.v)}</v></c>`;
  if (typeof c.v === 'number' && Number.isFinite(c.v)) return `<c r="${ref}"${sa}><v>${c.v}</v></c>`;
  return `<c r="${ref}"${sa} t="inlineStr"><is><t xml:space="preserve">${esc(c.v)}</t></is></c>`;
}

function sheetXml(sh) {
  const rows = sh.rows.map((r, ri) => `<row r="${ri + 1}">${(r || []).map((c, ci) => cellXml(c, `${colName(ci)}${ri + 1}`)).join('')}</row>`).join('');
  const cols = sh.widths ? `<cols>${sh.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>` : '';
  const pane = sh.freeze ? '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>' : '';
  const width = Math.max(1, ...sh.rows.map((r) => (r || []).length));
  const filter = sh.filter && sh.rows.length > 1 ? `<autoFilter ref="A1:${colName(width - 1)}${sh.rows.length - 1}"/>` : '';
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${pane}${cols}<sheetData>${rows}</sheetData>${filter}</worksheet>`;
}

